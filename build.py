"""
build.py: turns the lesson READMEs into lessons.js, which index.html reads.

The lesson folders are the single source of truth. Edit a README.md, run
    python build.py
and the website picks up the change. Needs:  pip install markdown pygments

LEARN: the site is plain HTML, so it can't read markdown on its own. Converting
it once, ahead of time, keeps the page fast and free of extra libraries.
"""
import json
import re
from pathlib import Path

import markdown

ROOT = Path(__file__).parent
REPO = "https://github.com/GubbGub/python-intro/blob/main"


def lesson(folder: Path) -> dict:
    text = (folder / "README.md").read_text(encoding="utf-8")

    # "# Lesson 2 · Strings"  ->  number 2, title "Strings"
    m = re.match(r"#\s*Lesson\s+(\d+)\s*·\s*(.+)\n", text)
    num, title = int(m.group(1)), m.group(2).strip()
    text = text[m.end():]

    # "**Time:** ~40 minutes (...)"  ->  "~40 min"
    t = re.search(r"\*\*Time:\*\*\s*(~?\d+)\s*min\w*(.*)\n", text)
    time = f"{t.group(1)} min" if t else ""
    time_note = t.group(2).strip(" ()") if t else ""
    if t:
        text = text[:t.start()] + text[t.end():]

    # let markdown inside <details> render (python-markdown needs markdown="1")
    text = text.replace("<details>", '<details markdown="1">')
    html = markdown.markdown(
        text,
        extensions=["fenced_code", "tables", "md_in_html", "codehilite"],
        extension_configs={"codehilite": {"guess_lang": False, "css_class": "hl"}},
    )
    files = [f for f in ("example.py", "exercise.py", "solution.py") if (folder / f).exists()]
    return {
        "num": num,
        "slug": folder.name,
        "title": title,
        "time": time,
        "timeNote": time_note,
        "html": html,
        "files": [{"name": f, "url": f"{REPO}/{folder.name}/{f}"} for f in files],
    }


def upcoming() -> list:
    """Roadmap rows marked 'coming soon' in the main README."""
    rows = []
    for line in (ROOT / "README.md").read_text(encoding="utf-8").splitlines():
        m = re.match(r"\|\s*(\d+)\s*\|\s*(.+?)\s*\|.*coming soon", line)
        if m:
            title = re.sub(r"`([^`]+)`", r"<code>\1</code>", m.group(2))
            rows.append({"num": int(m.group(1)), "title": title})
    return rows


if __name__ == "__main__":
    lessons = [lesson(d) for d in sorted(ROOT.glob("[0-9][0-9]-*")) if (d / "README.md").exists()]
    out = ("// Generated by build.py from the lesson READMEs. Don't edit by hand.\n"
           f"window.LESSONS = {json.dumps(lessons, ensure_ascii=False, indent=1)};\n"
           f"window.UPCOMING = {json.dumps(upcoming(), ensure_ascii=False)};\n")
    (ROOT / "lessons.js").write_text(out, encoding="utf-8")
    print(f"lessons.js: {len(lessons)} lessons, {len(upcoming())} coming soon")
